def _pivot_local(level) -> tuple[float, float, float]:
    """Centro del craneo de un nivel: centroide de area de las caras de la cabeza.

    Solo cuentan las ``head_faces`` primeras caras (fuera cuello y peana), asi
    que el pivote cae entre orejas y ojos y no en el centro del busto. La
    componente ``x`` se fuerza a 0 porque la malla es simetrica y el centroide
    numerico arrastra error de redondeo (~1e-4).
    """
    verts = level["verts"]
    total = 0.0
    acc = [0.0, 0.0, 0.0]
    for face in level["faces"][: level["head_faces"]]:
        points = [verts[i] for i in face]
        for k in range(1, len(points) - 1):
            a, b, c = points[0], points[k], points[k + 1]
            u = (b[0] - a[0], b[1] - a[1], b[2] - a[2])
            v = (c[0] - a[0], c[1] - a[1], c[2] - a[2])
            cx = u[1] * v[2] - u[2] * v[1]
            cy = u[2] * v[0] - u[0] * v[2]
            cz = u[0] * v[1] - u[1] * v[0]
            area = 0.5 * (cx * cx + cy * cy + cz * cz) ** 0.5
            if area <= 0.0:
                continue
            total += area
            for i in range(3):
                acc[i] += area * (a[i] + b[i] + c[i]) / 3.0
    if total <= 0.0:
        return (0.0, 0.0, 0.0)
    return (
        0.0,
        round(acc[1] / total, 4),
        round(acc[2] / total, 4),
    )


