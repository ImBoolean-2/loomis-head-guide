# fino (ver :func:`_pivot_local`). Es una constante, no depende de ``detail``.
PIVOT_LOCAL = _pivot_local(ASARO_CLEAN_LEVELS[LEVEL_COUNT - 1])


def neck_flags(level):
    """Flag por cara: True si la cara es de cuello o peana."""
    return ASARO_CLEAN_LEVELS[level]["neck"]


def get_level(detail):
    """Nivel de detalle pedido, acotado a los que existen."""
    try:
        index = int(round(float(detail)))
    except (TypeError, ValueError):
        index = 1
    return ASARO_CLEAN_LEVELS[max(0, min(LEVEL_COUNT - 1, index))]
