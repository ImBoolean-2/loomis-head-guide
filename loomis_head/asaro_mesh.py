def neck_flags(level):
    """Flag por cara: True si la cara es de cuello o peana."""
    data = ASARO_LEVELS[level]
    head = data["head_faces"]
    return tuple(i >= head for i in range(len(data["faces"])))


def get_level(detail):
    """Nivel de detalle pedido, acotado a los que existen."""
    try:
        index = int(round(float(detail)))
    except (TypeError, ValueError):
        index = 1
    return ASARO_LEVELS[max(0, min(LEVEL_COUNT - 1, index))]
